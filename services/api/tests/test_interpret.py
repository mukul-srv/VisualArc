"""26a interpretation: DIMENSION units check, block symbol recognition, gap healing, suggestions.
The fixture is generated by scripts/make_fixture_interpret.py (its plan is documented there)."""

import importlib.util
from dataclasses import replace
from pathlib import Path

import ezdxf
import pytest

from api.engine.adapters.dxf.reader import read_dxf
from api.engine.settings import DEFAULTS

ROOT = Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location("make_fixture_interpret", ROOT / "scripts/make_fixture_interpret.py")
_mk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mk)


def _read(tmp_path, settings=DEFAULTS, **kw):
    return read_dxf(_mk.build(tmp_path / "f.dxf", **kw), 3000, ceiling_height=3000, settings=settings)


def _by(p, code):
    return [i for i in p.issues if i.code == code]


def _floor(p):
    return p.buildings[0].floors[0]


def test_committed_fixture_is_the_generated_one(tmp_path):
    assert (ROOT / "fixtures/input/fixture_interpret.dxf").is_file()
    a, b = _read(tmp_path), read_dxf(ROOT / "fixtures/input/fixture_interpret.dxf", 3000, ceiling_height=3000)
    assert [i.code for i in a.issues] == [i.code for i in b.issues]


def test_block_symbols_recognised_with_provenance_and_confidence(tmp_path):
    p = _read(tmp_path)
    rec = {i.message.split("'")[1]: i for i in _by(p, "block_symbol_recognised")}
    assert set(rec) == {"DOOR_900", "WIN_1200", "STAIR_RUN"}
    assert all("confidence" in i.message and i.sources for i in rec.values())
    kinds = sorted(o.kind for o in _floor(p).openings)
    assert kinds == ["door", "window"]  # window from the block box, door from the gap its swing marks
    assert _by(p, "opening_from_block") and _by(p, "unmarked_gap_bridged")
    assert _floor(p).stairs or _by(p, "stair_direction_missing")  # stair outline made; direction not guessed


def test_name_only_block_is_ambiguous_with_a_candidate_not_placed(tmp_path):
    p = _read(tmp_path)
    (i,) = _by(p, "block_symbol_ambiguous")
    assert "STAIR_NOTE" in i.message
    assert [(s.kind, s.value) for s in i.suggestions] == [("layer_role", "stair")]
    assert len(_by(p, "stair_direction_missing")) == 1  # only STAIR_RUN made a stair; STAIR_NOTE made nothing


def test_small_gap_healed_and_reported_large_gap_left(tmp_path):
    p = _read(tmp_path)
    healed = _by(p, "wall_gap_healed")
    assert len(healed) == 2 and all("20.0 mm" in i.message and len(i.sources) == 2 for i in healed)
    assert healed[0].suggestions[0].kind == "gap_close"
    (gap,) = _by(p, "unmarked_wall_gap")  # the 200 mm gap is beyond tolerance: reported, not healed
    assert "200 mm" in gap.message


def test_off_tolerance_gap_stays_unhealed(tmp_path):
    p = _read(tmp_path, settings=replace(DEFAULTS, heal_gap_max_mm=10.0))
    assert not _by(p, "wall_gap_healed")
    assert len(_by(p, "unmarked_wall_gap")) == 2  # the 20 mm and the 200 mm gap, both still reported


def test_healing_can_be_switched_off(tmp_path):
    assert not _by(_read(tmp_path, settings=replace(DEFAULTS, heal_wall_gaps=False)), "wall_gap_healed")


def test_heal_never_closes_a_gap_as_wide_as_a_wall(tmp_path):
    s = replace(DEFAULTS, heal_gap_max_mm=500.0, wall_thickness_min_mm=15.0)  # a 20 mm gap is now wall-sized
    assert not _by(_read(tmp_path, settings=s), "wall_gap_healed")


def test_matching_dimension_raises_nothing(tmp_path):
    assert not _by(_read(tmp_path), "dimension_scale_mismatch")


def test_dimension_mismatch_suggests_units_and_changes_nothing(tmp_path):
    ok, bad = _read(tmp_path), _read(tmp_path, dim_text="60000")
    (i,) = _by(bad, "dimension_scale_mismatch")
    assert i.severity == "warning" and i.sources
    assert [(s.kind, s.value) for s in i.suggestions] == [("units", "cm")]  # 60000 reads as cm
    assert [w.centreline for w in _floor(bad).walls] == [w.centreline for w in _floor(ok).walls]  # never applied


def test_wrong_header_units_found_from_dimension(tmp_path):
    p = _read(tmp_path, units=ezdxf.units.M)  # header says metres, coordinates are mm
    (i,) = _by(p, "dimension_scale_mismatch")
    assert [(s.kind, s.value) for s in i.suggestions] == [("units", "mm")]
    assert "x0.001" in i.message


def test_unmapped_layer_hint_carries_a_structured_suggestion(tmp_path):
    doc = ezdxf.readfile(_mk.build(tmp_path / "g.dxf", blocks=False))
    doc.layers.add("PUERTAS")
    doc.modelspace().add_line((0, 0), (10, 10), dxfattribs={"layer": "PUERTAS"})
    doc.saveas(tmp_path / "g.dxf")
    p = read_dxf(tmp_path / "g.dxf", 3000, ceiling_height=3000)
    (i,) = [i for i in _by(p, "unmapped_layer") if "PUERTAS" in i.message]
    assert [(s.kind, s.value) for s in i.suggestions] == [("layer_role", "door")]


LOCAL = ROOT / "fixtures" / "local"


@pytest.mark.parametrize("name", ["cadcraft-sample-house.dxf", "draftcraft-apartment.dxf"])
def test_local_drawings_interpret_without_crash(name):
    if not (LOCAL / name).is_file():
        pytest.skip("local fixture absent")
    p = read_dxf(LOCAL / name, 2700, ceiling_height=2700, user_units="mm")
    for i in _by(p, "block_symbol_recognised") + _by(p, "wall_gap_healed"):
        assert i.sources  # nothing recognised or healed without provenance
