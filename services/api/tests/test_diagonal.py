ROOT = Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location("make_fixture_diagonal", ROOT / "scripts/make_fixture_diagonal.py")
_mk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mk)
H, S2 = _mk.H, math.sqrt(2)


def _read(tmp_path, **kw):
    return read_dxf(_mk.build(tmp_path / "d.dxf", **kw), 2700, ceiling_height=2700)


def _floor(p):
    return p.buildings[0].floors[0]


def _diag(floor):
    (w,) = [w for w in floor.walls if w.centreline.start[0] != w.centreline.end[0] and w.centreline.start[1] != w.centreline.end[1]]
    return w


def test_committed_fixture_is_the_generated_one(tmp_path):
    a = _read(tmp_path)
    b = read_dxf(ROOT / "fixtures/input/fixture_diagonal.dxf", 2700, ceiling_height=2700)
    assert a.buildings[0].floors[0].model_dump() == b.buildings[0].floors[0].model_dump()


def test_diagonal_wall_length_angle_thickness_and_role(tmp_path):
    f = _floor(_read(tmp_path))
    assert len(f.walls) == 5
    w = _diag(f)
    (x0, y0), (x1, y1) = w.centreline.start, w.centreline.end
    assert math.degrees(math.atan2(y1 - y0, x1 - x0)) == pytest.approx(135.0, abs=1e-6)
    assert w.thickness.value == pytest.approx(2 * H, abs=1e-6) and w.thickness.source == "source_extracted"
    # the centreline is the paired faces' overlap: between the mitred inner-face ends, 2000*sqrt(2) minus 2*h*tan(22.5)
    assert math.dist((x0, y0), (x1, y1)) == pytest.approx(2000 * S2 - 2 * H * math.tan(math.radians(22.5)), abs=1e-6)
    assert w.role == "exterior"


def test_closed_room_with_a_diagonal_wall_matches_the_hand_calculation(tmp_path):
    p = _read(tmp_path)
    (room,) = _floor(p).rooms
    perimeter = 6000 + 3000 + 2000 * S2 + 4000 + 5000
    cot = 3 * 1.0 + 2 / math.tan(math.radians(135 / 2))  # interior angles: 90 x3, 135 x2
    expected = 28e6 - perimeter * H + H * H * cot
    assert room.area.value == pytest.approx(expected, rel=1e-9)
    assert len(_floor(p).junctions) == 5
    assert not [i for i in p.issues if i.code in ("room_outline_open", "no_closed_rooms", "non_orthogonal_segment")]


def test_window_on_the_diagonal_wall(tmp_path):
    f = _floor(_read(tmp_path))
    (o,) = f.openings
    w = _diag(f)
    assert o.kind == "window" and o.wall_id == w.id and o.width.value == pytest.approx(1000, abs=1e-6)
    p0, (ux, uy) = _mk.diagonal_frame()[:2]
    along = [(q[0] - p0[0]) * ux + (q[1] - p0[1]) * uy for q in (o.span.start, o.span.end)]
    assert along == pytest.approx([800.0, 1800.0], abs=1e-6)  # where the marker was drawn, on the centreline
    wx, wy = w.centreline.start
    assert o.offset.value == pytest.approx(math.dist((wx, wy), o.span.start), abs=1e-6)


def test_extrusion_places_wall_and_opening_parts_on_the_diagonal(tmp_path):
    f = _floor(_read(tmp_path))
    w = _diag(f)
    meshes = build_meshes(f)
    m = meshes[w.id]
    assert m.is_watertight
    (xa, ya), (xb, yb) = w.centreline.start, w.centreline.end
    assert m.bounds[0][0] == pytest.approx(min(xa, xb) - H / S2, abs=1e-6)  # footprint = centreline +- h across it
    assert m.bounds[1][1] == pytest.approx(max(ya, yb) + H / S2, abs=1e-6)
    assert m.bounds[0][2] == pytest.approx(0.0, abs=1e-6) and m.bounds[1][2] == pytest.approx(2700, abs=1e-6)
    parts = build_opening_parts(f)
    frame = parts[f"{f.openings[0].id}-frame"][2]
    o = f.openings[0]
    mid = np.mean([o.span.start, o.span.end], axis=0)
    assert np.hypot(*(frame.centroid[:2] - mid)) < 1.0  # symmetric frame: centred on the opening


def test_glb_and_ifc_export_with_a_diagonal_wall(tmp_path):
    p = _read(tmp_path)
    scene = build_scene(p)
    assert len(export_glb(scene)) > 1000
    data, _ = build_ifc([(p, (0.0, 0.0))])
    assert b"IFCWALL" in data.upper()


def test_older_axis_only_opening_still_validates():
    o = {"id": "opening-001", "kind": "window", "wall_id": "w", "span": LineGeometry(start=(0, 0), end=(100, 0)),
             "offset": {"value": 0, "source": "source_extracted"}, "width": {"value": 100, "source": "source_extracted"},
             "height": {"value": 1, "source": "defaulted"}, "sill_height": {"value": 0, "source": "defaulted"},
             "sources": [{"layer": "A", "entity_handle": "1"}]}
    assert Opening.model_validate(o).span.end == (100, 0)
    with pytest.raises(ValueError):
        Opening.model_validate({**o, "span": LineGeometry(start=(100, 100), end=(0, 0))})  # diagonal runs to +y


def test_lone_diagonal_pair_pairs_and_unpaired_line_is_reported():
    d = 200 / S2  # 200 mm across a 45 degree wall
    s = [Segment("A", "A-WALL", (0, 0), (3000, 3000)), Segment("B", "A-WALL", (-d, d), (3000 - d, 3000 + d))]
    walls, issues = pair_walls(s)
    assert len(walls) == 1 and walls[0].thickness == pytest.approx(200, abs=1e-6) and not issues
    walls, issues = pair_walls([s[0]])
    assert not walls and [i.code for i in issues] == ["unpaired_segment"]


def test_diagonal_walls_off_reports_them_unread(tmp_path):
    p = read_dxf(_mk.build(tmp_path / "off.dxf"), 2700, ceiling_height=2700,
                 settings=replace(DEFAULTS, diagonal_walls=False))
    assert any(i.code == "non_orthogonal_segment" for i in p.issues)
    assert len(_floor(p).walls) == 4


def test_window_marker_off_every_wall_direction_is_reported_not_dropped(tmp_path):
    import ezdxf

    path = _mk.build(tmp_path / "m.dxf")
    doc = ezdxf.readfile(path)
    doc.modelspace().add_lwpolyline([(1000, 1000), (1100, 1100), (1050, 1150), (950, 1050)], close=True,
                                    dxfattribs={"layer": "A-GLAZ"})  # a rectangle turned 45 deg, in the room, on no wall
    doc.saveas(path)
    p = read_dxf(path, 2700, ceiling_height=2700)
    assert [i.code for i in p.issues if i.code.startswith("opening_marker")] == ["opening_marker_outside_wall"]
